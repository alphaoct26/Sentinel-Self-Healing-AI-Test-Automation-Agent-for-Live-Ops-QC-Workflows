def reset_test_file():
    with open(TEST_FILE, "w", encoding="utf-8") as f:
        f.write(BASELINE_TEST_CODE)

def set_drift_mode(mode_id):
    try:
        r = requests.post(f"{TARGET_APP_URL}/api/drift", json={"mode": mode_id}, timeout=3)
        return r.status_code == 200
    except Exception as e:
        print(f"Error setting drift mode {mode_id}: {e}")
        return False

def run_benchmark():
    print("=" * 80)
    print("SENTINEL LIVE BENCHMARK EXECUTION (24 MUTATION SCENARIOS)")
    print("=" * 80)

    results = []

    for idx, sc in enumerate(SCENARIOS, 1):
        mode = sc["id"]
        cat = sc["category"]
        desc = sc["description"]
        gt = sc["ground_truth"]

        print(f"\n[{idx:02d}/24] Running Scenario: {mode} ({cat})")
        print(f"       Description: {desc}")

        # 1. Reset baseline test file
        reset_test_file()

        # 2. Set target app drift mode
        set_drift_mode(mode)
        time.sleep(0.3)

        # 3. Execute initial test run
        run_res, run_log_path = run_test_suite()
        initial_status = run_res["status"]
        print(f"       Initial Test Status: {initial_status}")

        diagnosis_class = "NONE"
        confidence = 0.0
        sentinel_action = "NONE"
        verification_result = "PASSED" if initial_status == "PASSED" else "FAILED"

        if initial_status == "PASSED":
            sentinel_action = "Baseline / Locator Robust (No repair needed)"
            outcome = "CORRECT_PASS"
        else:
            # 4. Run Sentinel self-healer
            healed = heal_last_run()

            # Inspect latest repair log
            repair_dirs = sorted([d for d in REPAIRS_DIR.glob("*") if d.is_dir()], key=lambda p: p.stat().st_mtime, reverse=True)
            if repair_dirs:
                edit_log = repair_dirs[0] / "edit_log.json"
                if edit_log.exists():
                    try:
                        with open(edit_log, "r", encoding="utf-8") as f:
                            edata = json.load(f)
                            diagnosis_class = edata.get("classification", "UNKNOWN")
                            confidence = edata.get("confidence", 0.0)
                            verification_result = edata.get("verification_result", "FAILED")
                    except Exception:
                        pass

            if verification_result == "PASSED":
                sentinel_action = "Auto-Patched & Verified"
                if gt == "COSMETIC_DRIFT":
                    outcome = "TRUE_HEAL"
                else:
                    outcome = "FALSE_HEAL" # Falsely patched a real bug!
            elif verification_result == "HUMAN_REVIEW_REQUIRED":
                sentinel_action = "Safeguard Triggered (Declined Patch)"
                if gt in ["REAL_BUG"]:
                    outcome = "SAFEGUARD_HELD"
                else:
                    outcome = "FALSE_SAFEGUARD" # Declined a cosmetic drift
            else:
                sentinel_action = "Patch Verification Failed (Rolled Back)"
                outcome = "PATCH_FAILED"

        print(f"       AI Classification: {diagnosis_class} ({confidence * 100:.1f}%)")
        print(f"       Sentinel Action:   {sentinel_action}")
        print(f"       Verification:      {verification_result}")
        print(f"       Outcome:           {outcome}")

        results.append({
            "index": idx,
            "scenario": mode,
            "category": cat,
            "description": desc,
            "ground_truth": gt,
            "initial_status": initial_status,
            "classification": diagnosis_class,
            "confidence": confidence,
            "sentinel_action": sentinel_action,
            "verification": verification_result,
            "outcome": outcome
        })

    # Reset baseline test file and target app to NORMAL
    reset_test_file()
    set_drift_mode("NORMAL")

    # Compute Aggregate Metrics
    total = len(results)
    cosmetic_scenarios = [r for r in results if r["ground_truth"] == "COSMETIC_DRIFT"]
    real_bug_scenarios = [r for r in results if r["ground_truth"] == "REAL_BUG"]
    dom_reorg_scenarios = [r for r in results if r["ground_truth"] in ["DOM_REORG", "TIMING", "CLEAN"]]

    total_cosmetic = len(cosmetic_scenarios)
    true_heals = sum(1 for r in cosmetic_scenarios if r["outcome"] == "TRUE_HEAL")
    unhealed_cosmetic = total_cosmetic - true_heals

    total_real_bugs = len(real_bug_scenarios)
    safeguards_held = sum(1 for r in real_bug_scenarios if r["outcome"] == "SAFEGUARD_HELD")
    false_heals = sum(1 for r in real_bug_scenarios if r["outcome"] == "FALSE_HEAL")

    total_patches_attempted = sum(1 for r in results if r["sentinel_action"] == "Auto-Patched & Verified" or r["outcome"] in ["TRUE_HEAL", "FALSE_HEAL"])
    heal_precision = (true_heals / total_patches_attempted * 100.0) if total_patches_attempted > 0 else 0.0
    false_heal_rate = (false_heals / total_real_bugs * 100.0) if total_real_bugs > 0 else 0.0
    safeguard_rate = (safeguards_held / total_real_bugs * 100.0) if total_real_bugs > 0 else 0.0

    print("\n" + "=" * 80)
    print("BENCHMARK SUMMARY METRICS")
    print("=" * 80)
    print(f"Total Mutation Scenarios:            {total}")
    print(f"Cosmetic Drift Scenarios:             {total_cosmetic}")
    print(f"  - Successfully Healed (True Heals): {true_heals}")
    print(f"  - Unhealed / Safeguarded:           {unhealed_cosmetic}")
    print(f"Genuine Bug / Regression Scenarios:   {total_real_bugs}")
    print(f"  - Safeguard Held (No Bad Patch):    {safeguards_held}")
    print(f"  - False Heals (Bad Patches):        {false_heals}")
    print(f"Pass-through / Robust (DOM/Timing):   {len(dom_reorg_scenarios)}")
    print(f"--------------------------------------------------------------------------------")
    print(f"Heal Precision:                      {heal_precision:.1f}%")
    print(f"False-Heal Rate:                     {false_heal_rate:.1f}%")
    print(f"Safeguard Success Rate:              {safeguard_rate:.1f}%")
    print("=" * 80)

    # Save benchmark results to artifacts
    bench_data = {
        "summary": {
            "total_scenarios": total,
            "cosmetic_drift_total": total_cosmetic,
            "true_heals": true_heals,
            "real_bug_total": total_real_bugs,
            "safeguards_held": safeguards_held,
            "false_heals": false_heals,
            "heal_precision_pct": round(heal_precision, 1),
            "false_heal_rate_pct": round(false_heal_rate, 1),
            "safeguard_success_rate_pct": round(safeguard_rate, 1)
        },
        "results": results
    }

    out_json = BASE_DIR / "artifacts" / "benchmark_results.json"
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(bench_data, f, indent=2)

    print(f"\n[Benchmark] Results written to {out_json}")
    return bench_data

if __name__ == "__main__":
    run_benchmark()
